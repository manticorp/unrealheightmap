#!/usr/bin/env node
/**
 * Generates the machine-readable files for AI agents and LLMs:
 *   - url-params.json   every URL setting, from src/url-state.ts + src/url-params-meta.ts
 *   - <page>.md         Markdown mirror of each documentation page
 *   - llms-full.txt     all documentation in one Markdown file
 *
 * Run with `npm run docs:agents`. The output is committed because GitHub Pages serves the repo.
 * `tests/agent-docs.test.ts` fails when url-params.json is out of date.
 */
const fs = require('fs');
const path = require('path');
const TurndownService = require('turndown');
const {parse} = require('node-html-parser');

const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://manticorp.github.io/unrealheightmap/';

// Pages mirrored to Markdown, in the order they appear in llms-full.txt.
const PAGES = [
  'instructions', 'guides', 'guide-unreal', 'guide-blender', 'guide-godot', 'guide-unity',
  'guide-3d-printing', 'guide-other', 'examples', 'rights',
];

const buildUrlParams = () => {
  require('ts-node').register({transpileOnly: true, compilerOptions: {module: 'commonjs'}});
  const {buildUrlParamsSpec} = require('../src/url-params-meta');
  return JSON.stringify(buildUrlParamsSpec(), null, 2) + '\n';
};

const turndown = new TurndownService({headingStyle: 'atx', codeBlockStyle: 'fenced', bulletListMarker: '-'});
turndown.remove(['script', 'style', 'svg', 'video', 'iframe', 'noscript']);

/** Make relative links absolute, pointing at the Markdown mirror for our own pages. */
const absolutise = (md, page) => md.replace(/\]\(([^)\s]+)\)/g, (whole, href) => {
  if (/^(https?:|mailto:|data:)/.test(href)) return whole;
  if (href.startsWith('#')) return `](${SITE}${page}.md${href})`;
  const m = href.match(/^([a-z0-9-]+)\.html(#.*)?$/i);
  if (m && PAGES.includes(m[1])) return `](${SITE}${m[1]}.md${m[2] || ''})`;
  return `](${new URL(href, SITE).href})`;
});

const htmlToMarkdown = (page) => {
  const html = fs.readFileSync(path.join(ROOT, `${page}.html`), 'utf8');
  const root = parse(html);
  const title = (root.querySelector('title')?.text || page).trim();
  const description = root.querySelector('meta[name="description"]')?.getAttribute('content') || '';
  const main = root.querySelector('main');
  main.querySelectorAll('.guide-meta').forEach((n) => n.remove());
  const body = absolutise(turndown.turndown(main.innerHTML), page).replace(/\n{3,}/g, '\n\n').trim();
  const header = [
    `<!-- Generated from ${page}.html by scripts/build-agent-docs.js. Do not edit by hand. -->`,
    `Source: ${SITE}${page}.html`,
    `Title: ${title}`,
    description ? `Summary: ${description}` : '',
  ].filter(Boolean).join('\n');
  return {title, markdown: `${header}\n\n${body}\n`};
};

// ---------------------------------------------------------------------------------------------
// Structured data (JSON-LD), canonical URL, Open Graph tags and llms.txt link, injected between
// markers in each page's <head>. Regenerated on every run, so the FAQ stays in step with the page.
// ---------------------------------------------------------------------------------------------
const START = '<!-- agent-meta:start (generated by scripts/build-agent-docs.js) -->';
const END = '<!-- agent-meta:end -->';
const APP_NAME = '16/32 Bit Heightmap Generator';
const AUTHOR = {'@type': 'Person', name: 'Harry Mustoe-Playfair', url: 'https://github.com/manticorp'};

// Descriptions for pages that have no <meta name="description"> of their own.
const FALLBACK_DESCRIPTION = {
  index: 'Free browser-based tool that turns real-world elevation data into 16-bit PNG and 16/32-bit EXR heightmaps, texture maps, 3D models and posters for Unreal Engine, Godot, Blender, Unity and 3D printing.',
  examples: 'Things people have made with heightmaps from the 16/32 Bit Heightmap Generator, including real-terrain snowmobile maps for the game Sledders.',
  rights: 'Licences, attribution and usage rights for the elevation data and map imagery used by the 16/32 Bit Heightmap Generator.',
};

const FEATURES = [
  '16-bit PNG, 16/32-bit OpenEXR and GeoTIFF heightmaps',
  'Worldwide elevation including 0.25 to 10 m lidar (Mapterhorn, USGS 3DEP) and ocean bathymetry (NOAA ETOPO)',
  'Mars, Moon and Mercury elevation data',
  'Tiled, rotated, custom-shaped and seamless exports up to 8129 x 8129',
  'Normal, slope, curvature, ambient occlusion, flow, aspect and sunlight maps',
  'OpenStreetMap masks, road, river and lake carving, splines and scatter points',
  'Real tree maps from measured canopy data',
  'STL, OBJ, GLB and 3MF 3D models with buildings, labels and lithophanes',
  'Contours, laser-cut layers and shaded-relief posters',
  'Unreal Engine scale values, world files and Blender/Unreal import scripts',
  'Shareable links that store every setting in the URL',
  'Runs entirely in the browser; nothing is uploaded',
];

const textOf = (node) => node.text.replace(/\s+/g, ' ').trim();

const faqEntities = (root) => root.querySelectorAll('#faq details').map((d) => {
  const q = textOf(d.querySelector('summary'));
  d.querySelector('summary').remove();
  d.querySelectorAll('figure, img, .columns').forEach((n) => n.remove());
  return {'@type': 'Question', name: q, acceptedAnswer: {'@type': 'Answer', text: textOf(d)}};
});

const pageUrl = (page) => (page === 'index' ? SITE : `${SITE}${page}.html`);

const structuredData = (page, root, title, description) => {
  const url = pageUrl(page);
  const h1 = root.querySelector('h1') ? textOf(root.querySelector('h1')) : title;
  const publisher = {'@type': 'Organization', name: 'unrealheightmap', url: SITE};
  const data = [];

  if (page === 'index') {
    data.push({
      '@context': 'https://schema.org',
      '@type': 'WebApplication',
      name: APP_NAME,
      alternateName: ['Unreal Heightmap', 'unrealheightmap'],
      url: SITE,
      description,
      applicationCategory: 'DesignApplication',
      applicationSubCategory: 'Terrain and heightmap generator',
      operatingSystem: 'Any (modern web browser)',
      browserRequirements: 'Requires JavaScript; WebGL for the 3D preview',
      isAccessibleForFree: true,
      offers: {'@type': 'Offer', price: '0', priceCurrency: 'USD'},
      license: 'https://github.com/manticorp/unrealheightmap/blob/main/LICENSE',
      softwareHelp: {'@type': 'WebPage', url: `${SITE}instructions.html`},
      sameAs: ['https://github.com/manticorp/unrealheightmap'],
      author: AUTHOR,
      featureList: FEATURES,
    });
    data.push({
      '@context': 'https://schema.org', '@type': 'WebSite', name: APP_NAME, url: SITE,
      description: 'Free heightmap generator for Unreal Engine, Godot, Blender, Unity and 3D printing.',
      inLanguage: 'en',
    });
    return data;
  }

  const crumbs = [{name: APP_NAME, item: SITE}];
  if (page.startsWith('guide-')) crumbs.push({name: 'Import Guides', item: `${SITE}guides.html`});
  crumbs.push({name: h1, item: url});
  data.push({
    '@context': 'https://schema.org', '@type': 'BreadcrumbList',
    itemListElement: crumbs.map((c, i) => ({'@type': 'ListItem', position: i + 1, name: c.name, item: c.item})),
  });

  if (page === 'instructions' || page.startsWith('guide-')) {
    data.push({
      '@context': 'https://schema.org', '@type': 'TechArticle', headline: h1, description, url,
      inLanguage: 'en', author: AUTHOR, publisher, isAccessibleForFree: true,
      isPartOf: {'@type': 'WebApplication', name: APP_NAME, url: SITE},
      proficiencyLevel: page === 'instructions' ? 'Beginner' : 'Expert',
    });
  } else if (page === 'guides') {
    const cards = root.querySelectorAll('a.box').filter((a) => /^guide-[a-z0-9-]+\.html$/.test(a.getAttribute('href') || ''));
    data.push({
      '@context': 'https://schema.org', '@type': 'CollectionPage', name: h1, description, url, inLanguage: 'en',
      mainEntity: {
        '@type': 'ItemList',
        itemListElement: cards.map((a, i) => ({
          '@type': 'ListItem', position: i + 1, name: textOf(a.querySelector('h2') || a), url: SITE + a.getAttribute('href'),
        })),
      },
    });
  } else {
    data.push({
      '@context': 'https://schema.org', '@type': page === 'examples' ? 'CollectionPage' : 'WebPage',
      name: h1, description, url, inLanguage: 'en', isPartOf: {'@type': 'WebSite', name: APP_NAME, url: SITE},
    });
  }

  if (page === 'instructions') {
    const entities = faqEntities(root);
    if (entities.length) data.push({'@context': 'https://schema.org', '@type': 'FAQPage', mainEntity: entities});
  }
  return data;
};

const escAttr = (v) => v.replace(/&/g, '&amp;').replace(/"/g, '&quot;');

const headBlock = (page, title, description, data, hasDescription) => {
  const url = pageUrl(page);
  const lines = [
    START,
    `<link rel="canonical" href="${url}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="${escAttr(APP_NAME)}">`,
    `<meta property="og:title" content="${escAttr(title)}">`,
    `<meta property="og:description" content="${escAttr(description)}">`,
    `<meta property="og:url" content="${url}">`,
    `<meta name="twitter:card" content="summary">`,
    `<link rel="alternate" type="text/plain" href="${SITE}llms.txt" title="llms.txt">`,
  ];
  if (page !== 'index') lines.push(`<link rel="alternate" type="text/markdown" href="${SITE}${page}.md">`);
  if (!hasDescription) lines.push(`<meta name="description" content="${escAttr(description)}">`);
  for (const d of data) {
    // "<" is escaped so the JSON can never close the script element
    lines.push(`<script type="application/ld+json">${JSON.stringify(d).replace(/</g, '\\u003c')}</script>`);
  }
  lines.push(END);
  return lines.map((l, i) => (i === 0 ? l : '    ' + l)).join('\n');
};

const injectHead = (page) => {
  const file = path.join(ROOT, `${page}.html`);
  let html = fs.readFileSync(file, 'utf8');
  // Parse without our own block so a previous run can't affect the result
  const existing = new RegExp(`[ \\t]*${START.replace(/[()]/g, '\\$&')}[\\s\\S]*?${END}\\n?`);
  const clean = html.replace(existing, '');
  const root = parse(clean);
  const title = (root.querySelector('title')?.text || APP_NAME).trim().replace(/&amp;/g, '&');
  const own = root.querySelector('meta[name="description"]')?.getAttribute('content');
  const description = own || FALLBACK_DESCRIPTION[page] || title;
  const block = headBlock(page, title, description, structuredData(page, root, title, description), !!own);
  if (existing.test(html)) {
    html = html.replace(existing, () => `    ${block}\n`);
  } else {
    html = html.replace(/(\n)(\s*)<link rel="stylesheet"/, (m, nl, ws) => `${nl}${ws}${block}\n${ws}<link rel="stylesheet"`);
  }
  fs.writeFileSync(file, html);
};

for (const page of ['index', ...PAGES]) injectHead(page);

const write = (file, content) => fs.writeFileSync(path.join(ROOT, file), content);

write('url-params.json', buildUrlParams());

const parts = [];
for (const page of PAGES) {
  const {markdown} = htmlToMarkdown(page);
  write(`${page}.md`, markdown);
  parts.push(markdown);
}

write('llms-full.txt', [
  '# 16/32 Bit Heightmap Generator: full documentation',
  '',
  `> Everything on ${SITE} in one file. Index: ${SITE}llms.txt`,
  `> URL settings spec (JSON): ${SITE}url-params.json`,
  '',
  parts.join('\n\n---\n\n'),
].join('\n'));

console.log(`Wrote url-params.json, llms-full.txt, ${PAGES.length} Markdown pages and head metadata for ${PAGES.length + 1} HTML pages.`);
