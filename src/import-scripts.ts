/**
 * Small helper scripts shipped next to an export, so the terrain lands in
 * Blender or Unreal at the right size without anyone typing scale values.
 *
 * The scripts are plain text built from the export's numbers. They only
 * reference files by name and look for them next to the script.
 */

export type HeightEncoding =
  /** 0–65535 (PNG) or 0–1 (EXR) spanning minHeight..maxHeight. */
  | 'normalised'
  /** Sample values are metres above sea level. */
  | 'metres';

export type ScriptTile = {
  /** Heightmap file for this tile. */
  file: string;
  /** Pixel offset of the tile's top-left corner in the full export. */
  startX: number;
  startY: number;
  width: number;
  height: number;
};

export type ImportScriptInput = {
  /** Base name used for objects and the script files. */
  name: string;
  /** Full export size in pixels. */
  width: number;
  height: number;
  /** Ground size of the full export in metres. */
  physWidth: number;
  physHeight: number;
  /** Real heights (metres) the normalised range maps to. */
  minHeight: number;
  maxHeight: number;
  encoding: HeightEncoding;
  /** File type of the heightmap: PNGs read as 0–1 in Blender, EXR/TIFF as raw values. */
  format: 'png' | 'exr' | 'tif';
  /** One entry for a single file, several for a tiled export. */
  tiles: ScriptTile[];
  /** Optional colour texture for the whole area (e.g. the albedo export). */
  albedoFile?: string;
  /** Optional extra mask/texture files to load (normal, slope, OSM layers…). */
  extraFiles?: string[];
};

export type ScriptFile = {filename: string, contents: string};

const pyString = (s: string) => JSON.stringify(s);
const pyNum = (n: number, digits = 6) => Number.isFinite(n) ? Number(n.toFixed(digits)).toString() : '0';

/** Unreal's landscape Z scale for a 16-bit heightmap spanning `range` metres (cm per 1/128 step). */
export const unrealZScale = (range: number) => range * 100 / 512;

/** Unreal's landscape X/Y scale: centimetres per heightmap pixel. */
export const unrealXYScale = (physWidth: number, width: number) => physWidth * 100 / Math.max(1, width);

/**
 * Landscape actor Z (cm) that puts normalised value 0 at minHeight, so sea
 * level ends up at Z = 0. Unreal treats 32768 as local zero.
 */
export const unrealZLocation = (minHeight: number, maxHeight: number) =>
  (minHeight + (maxHeight - minHeight) * 32768 / 65535) * 100;

/**
 * How a sample value read as 0–1 (Blender PNG) or raw (EXR/TIFF) turns into metres:
 * metres = offset + value * strength.
 */
export const blenderDisplacement = (input: ImportScriptInput) => {
  const range = Math.max(0, input.maxHeight - input.minHeight);
  if (input.encoding === 'normalised') {
    return {offset: input.minHeight, strength: range};
  }
  // Raw metres: Blender scales 16-bit PNGs to 0–1, float formats are read as-is
  return {offset: 0, strength: input.format === 'png' ? 65535 : 1};
};

/** Unreal Z scale and actor height for a 16-bit PNG: 32768 is local zero, 128 steps per Z-scale cm. */
export const unrealHeightSetup = (input: ImportScriptInput) => {
  const range = Math.max(0, input.maxHeight - input.minHeight);
  const metresPerStep = input.encoding === 'normalised' ? range / 65535 : 1;
  const offset = input.encoding === 'normalised' ? input.minHeight : 0;
  return {
    zScale: metresPerStep * 100 * 128,
    zLocation: (offset + 32768 * metresPerStep) * 100,
  };
};

export const blenderScript = (input: ImportScriptInput): string => {
  const range = Math.max(0, input.maxHeight - input.minHeight);
  const displacement = blenderDisplacement(input);
  const metresPerPxX = input.physWidth / Math.max(1, input.width);
  const metresPerPxY = input.physHeight / Math.max(1, input.height);
  const tiles = input.tiles.map(t =>
    `    (${pyString(t.file)}, ${t.startX}, ${t.startY}, ${t.width}, ${t.height}),`
  ).join('\n');
  const extras = (input.extraFiles || []).map(f => `    ${pyString(f)},`).join('\n');
  return `# Blender import script for ${input.name}
# Generated by https://manticorp.github.io/unrealheightmap/
#
# How to use: put this file in the same folder as the downloaded heightmap
# (and albedo, if you have one). In Blender open the Scripting workspace,
# Text > Open this file, then press Run Script (Alt+P).
#
# It builds a grid at real-world size in metres, displaces it with the
# heightmap and, if found, applies the albedo as the colour texture.

import bpy
import os

# --- Settings you can change -------------------------------------------------
# Vertices along the longer side of each tile. Higher = more detail, slower.
MAX_SUBDIVISIONS = 1024
# 1.0 = real size in metres. Use e.g. 0.001 for a kilometre-wide scene at 1 m.
SCALE = 1.0
# Leave empty to look next to this script (or in the current .blend's folder).
FOLDER = r""
# ---------------------------------------------------------------------------

NAME = ${pyString(input.name)}
# metres = HEIGHT_OFFSET + pixel value * HEIGHT_STRENGTH (heights ${pyNum(input.minHeight, 1)} to ${pyNum(input.maxHeight, 1)} m)
HEIGHT_OFFSET = ${pyNum(displacement.offset, 3)}
HEIGHT_STRENGTH = ${pyNum(displacement.strength, 3)}
METRES_PER_PX_X = ${pyNum(metresPerPxX, 9)}
METRES_PER_PX_Y = ${pyNum(metresPerPxY, 9)}
FULL_WIDTH = ${input.width}
FULL_HEIGHT = ${input.height}
TILES = [
${tiles}
]
ALBEDO = ${input.albedoFile ? pyString(input.albedoFile) : 'None'}
EXTRA_FILES = [
${extras}
]


def find_folder():
    if FOLDER:
        return bpy.path.abspath(FOLDER)
    for text in bpy.data.texts:
        if text.filepath and os.path.basename(text.filepath).startswith(NAME):
            return os.path.dirname(bpy.path.abspath(text.filepath))
    if bpy.data.filepath:
        return os.path.dirname(bpy.data.filepath)
    return os.path.join(os.path.expanduser("~"), "Downloads")


def load_image(folder, filename, colour):
    path = os.path.join(folder, filename)
    if not os.path.exists(path):
        print("Not found, skipping:", path)
        return None
    image = bpy.data.images.load(path, check_existing=True)
    image.colorspace_settings.name = "sRGB" if colour else "Non-Color"
    return image


def make_material(folder):
    mat = bpy.data.materials.new(NAME + "_terrain")
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    if bsdf:
        bsdf.inputs["Roughness"].default_value = 1.0
    if ALBEDO:
        image = load_image(folder, ALBEDO, True)
        if image and bsdf:
            tex = mat.node_tree.nodes.new("ShaderNodeTexImage")
            tex.image = image
            tex.location = (-400, 300)
            mat.node_tree.links.new(tex.outputs["Color"], bsdf.inputs["Base Color"])
    return mat


def build_tile(folder, mat, filename, start_x, start_y, width, height):
    image = load_image(folder, filename, False)
    if image is None:
        return None
    size_x = width * METRES_PER_PX_X * SCALE
    size_y = height * METRES_PER_PX_Y * SCALE
    longest = max(width, height)
    factor = min(1.0, MAX_SUBDIVISIONS / max(1, longest))
    subdiv_x = max(2, int(round(width * factor)))
    subdiv_y = max(2, int(round(height * factor)))

    bpy.ops.mesh.primitive_grid_add(x_subdivisions=subdiv_x, y_subdivisions=subdiv_y, size=1, calc_uvs=True)
    obj = bpy.context.active_object
    obj.name = os.path.splitext(filename)[0]
    obj.scale = (size_x, size_y, 1)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)

    # Centre the whole export on the origin, +Y north
    centre_x = (start_x + width / 2 - FULL_WIDTH / 2) * METRES_PER_PX_X * SCALE
    centre_y = (FULL_HEIGHT / 2 - start_y - height / 2) * METRES_PER_PX_Y * SCALE
    obj.location = (centre_x, centre_y, 0)

    tex = bpy.data.textures.new(obj.name + "_height", type="IMAGE")
    tex.image = image
    tex.extension = "EXTEND"
    mod = obj.modifiers.new("Heightmap", "DISPLACE")
    mod.texture = tex
    mod.texture_coords = "UV"
    mod.direction = "Z"
    mod.mid_level = 0.0
    mod.strength = HEIGHT_STRENGTH * SCALE
    obj.location.z = HEIGHT_OFFSET * SCALE

    if ALBEDO:
        # The albedo covers the whole export, so shift UVs to this tile's part of it
        uv = obj.data.uv_layers.active.data
        for loop in uv:
            u, v = loop.uv
            loop.uv = (
                (start_x + u * width) / FULL_WIDTH,
                1 - (start_y + (1 - v) * height) / FULL_HEIGHT,
            )
        # ...but the displacement wants the tile's own 0-1 UVs
        tile_uv = obj.data.uv_layers.new(name="HeightUV")
        for i, loop in enumerate(tile_uv.data):
            u, v = uv[i].uv
            loop.uv = (
                (u * FULL_WIDTH - start_x) / width,
                1 - ((1 - v) * FULL_HEIGHT - start_y) / height,
            )
        mod.uv_layer = "HeightUV"

    bpy.ops.object.shade_smooth()
    obj.data.materials.append(mat)
    return obj


def main():
    folder = find_folder()
    print("Loading terrain files from", folder)
    mat = make_material(folder)
    made = [build_tile(folder, mat, *tile) for tile in TILES]
    made = [o for o in made if o]
    for extra in EXTRA_FILES:
        load_image(folder, extra, False)
    if not made:
        raise RuntimeError("No heightmap files found in " + folder + ". Set FOLDER at the top of the script.")
    # Big terrains need a longer view distance
    extent = max(FULL_WIDTH * METRES_PER_PX_X, FULL_HEIGHT * METRES_PER_PX_Y) * SCALE
    for area in bpy.context.screen.areas:
        if area.type == "VIEW_3D":
            for space in area.spaces:
                if space.type == "VIEW_3D":
                    space.clip_end = max(space.clip_end, extent * 4)
    print("Created", len(made), "terrain object(s).")


main()
`;
};

export const unrealScript = (input: ImportScriptInput): string => {
  const {zScale, zLocation} = unrealHeightSetup(input);
  const xyScale = unrealXYScale(input.physWidth, input.width);
  return `# Unreal Engine helper for ${input.name}
# Generated by https://manticorp.github.io/unrealheightmap/
#
# Unreal can't create a landscape from Python, so:
#  1. Landscape mode > New > Import from File: pick the heightmap
#     (for tiles, pick the first tile; Unreal finds the rest when they use
#     the _x0_y0 naming). Add any layer weightmaps (OSM masks, height bands)
#     in the layer list there too.
#  2. Click Import, then select the new Landscape in the Outliner.
#  3. Tools > Execute Python Script... and choose this file
#     (needs the Python Editor Script Plugin, on by default in UE5).
#
# It sets the landscape's scale (and height, for normalised heightmaps) so
# the terrain is true to life, with sea level at Z = 0.

import unreal

XY_SCALE = ${pyNum(xyScale, 4)}   # centimetres per heightmap pixel
Z_SCALE = ${pyNum(zScale, 4)}    # heights ${pyNum(input.minHeight, 1)} to ${pyNum(input.maxHeight, 1)} m
Z_LOCATION = ${pyNum(zLocation, 2)}  # cm, so sea level ends up at Z = 0


def landscapes():
    subsystem = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
    selected = [a for a in subsystem.get_selected_level_actors() if isinstance(a, unreal.LandscapeProxy)]
    if selected:
        return selected
    found = [a for a in subsystem.get_all_level_actors() if isinstance(a, unreal.LandscapeProxy)]
    if len(found) == 1:
        return found
    return []


def main():
    targets = landscapes()
    if not targets:
        unreal.log_warning("Select the landscape you imported, then run this script again.")
        return
    with unreal.ScopedEditorTransaction("Set terrain scale"):
        for actor in targets:
            actor.set_actor_scale3d(unreal.Vector(XY_SCALE, XY_SCALE, Z_SCALE))
            location = actor.get_actor_location()
            actor.set_actor_location(unreal.Vector(location.x, location.y, Z_LOCATION), False, False)
            unreal.log("Scaled " + actor.get_actor_label() + " to XY " + str(XY_SCALE) + ", Z " + str(Z_SCALE))


main()
`;
};

export const readmeText = (input: ImportScriptInput): string => {
  const range = input.maxHeight - input.minHeight;
  const lines = [
    `${input.name}`,
    '',
    `Area: ${(input.physWidth / 1000).toFixed(3)} × ${(input.physHeight / 1000).toFixed(3)} km, ${input.width} × ${input.height} px`,
    `Heights: ${input.minHeight.toFixed(1)} m to ${input.maxHeight.toFixed(1)} m (range ${range.toFixed(1)} m)`,
    input.encoding === 'normalised'
      ? 'Heightmap values are normalised: black = lowest point, white = highest.'
      : 'Heightmap values are metres above sea level.',
    '',
    ...(input.format === 'png' ? [] : ['Unreal Engine imports 16-bit PNG heightmaps; export as PNG for Unreal.', '']),
    'Unreal Engine',
    `  Import scale X/Y: ${unrealXYScale(input.physWidth, input.width).toFixed(4)}  Z: ${unrealHeightSetup(input).zScale.toFixed(4)}  Location Z: ${unrealHeightSetup(input).zLocation.toFixed(0)} cm`,
    '  Or run unreal_set_scale.py after importing (see the comments at its top).',
    '',
    'Blender',
    '  Run blender_import.py from the Scripting workspace (Text > Open, then Run Script).',
    '',
  ];
  return lines.join('\n');
};

/** Everything to ship with an export. */
export const buildImportScripts = (input: ImportScriptInput): ScriptFile[] => {
  const files = [{filename: `${input.name}_blender_import.py`, contents: blenderScript(input)}];
  // Unreal landscapes only import 16-bit PNG/RAW heightmaps
  if (input.format === 'png') {
    files.push({filename: `${input.name}_unreal_set_scale.py`, contents: unrealScript(input)});
  }
  files.push({filename: `${input.name}_README.txt`, contents: readmeText(input)});
  return files;
};
